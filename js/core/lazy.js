/* Kurenai OS — core/lazy.js
   Loading on first use (quality W2, AP-01).

   WHY. Boot used to parse every script the app has: 17 MB, most of it
   curriculum content no first page needs. The scripts are still classic
   <script> tags (index.html runs from file://, invariant: no bundler), but
   the heavy ones now sit inside <template data-lazy="NAME"> blocks in
   index.html. A template's contents are inert, so the browser skips them at
   boot; this file loads a block the first time something needs it.

   THE MANIFEST IS index.html. A bundle is every <script src> inside the
   templates carrying its name, in document order. Nothing else lists the
   files: the service worker's precache and every test loader read the same
   tags (a test loader evaluates every tag it finds in the HTML text, so a
   test boot is EAGER and unchanged unless it asks for lazy mode).

   WHAT STANDS IN BEFORE A BUNDLE LOADS. js/data/lazy-index.js (GENERATED by
   tools/gen_lazy_index.mjs) holds the STRUCTURE of what the bundles
   register: which topics have content, each flashcard's schedule key, page
   and listing counts, a Code task's tier and concepts. Each is a STUB: an
   object carrying those light facts, which knows the names of the heavy
   fields it leaves out. Reading a light fact is free and right. Reading a
   left-out field is a MISS: it returns nothing, the bundle starts loading
   and the page on screen is redrawn when it arrives. A page that names what
   it needs (NEEDS below) never misses: KOS.show waits for its bundles
   first, behind a short "Loading…" placeholder.

   A miss outside a page (a ticker, a sweep) would compute from nothing, so
   smoke142 holds boot, Home and the background passes to ZERO misses and to
   the same saved state as an eager boot.

   KOS.lazy.need(names)   → Promise, resolved once every bundle is in
   KOS.lazy.ready(names)  → are they all in?
   KOS.lazy.all()         → need every bundle (search, the Assistant's tools)
   KOS.lazy.warm(first)   → fetch the rest in idle moments, after boot
   KOS.lazy.on(fn)        → fn(name) after a bundle has loaded
   KOS.lazy.stub / isStub → the stand-ins, for lazy-index.js and the
                            registries that replace them                  */
(function () {
  "use strict";
  window.KOS = window.KOS || {};
  /* this is the first of the app's own scripts: boot is timed from here to
     "kos-interactive" (js/main.js), as the measure "kos-boot" */
  try { performance.mark("kos-boot-start"); } catch (e) { /* no User Timing */ }

  /* A test boot may say how to load (tools/lib/app-harness.js, {lazy:true}).
     With no hook: a page whose scripts run natively has a current script and
     inert templates, so it is lazy; a loader that evaluates the HTML's tags
     in order has neither, and has already run everything: eager. */
  var HOOK = window.KOS_LAZY_HOOK || null;
  var LAZY = HOOK ? HOOK.mode === "lazy" : !!document.currentScript;

  var ST = {};                  /* name → {state: 0 idle | 1 loading | 2 in, p} */
  var FILES = null, WHOLE = false;
  var listeners = [];
  var MISSES = [];

  /* name → its files in document order, read from the templates. The list
     is whole only once the document has been read to its end. */
  function files() {
    if (FILES && WHOLE) return FILES;
    var out = {};
    var nodes = document.querySelectorAll("template[data-lazy]");
    for (var i = 0; i < nodes.length; i++) {
      var name = nodes[i].getAttribute("data-lazy");
      var root = nodes[i].content || nodes[i];
      var ss = root.querySelectorAll("script[src]");
      out[name] = out[name] || [];
      for (var j = 0; j < ss.length; j++) out[name].push(ss[j].getAttribute("src"));
    }
    FILES = out;
    WHOLE = document.readyState !== "loading";
    return FILES;
  }
  function st(name) { return ST[name] || (ST[name] = { state: LAZY ? 0 : 2, p: null }); }
  function names() { return Object.keys(files()); }
  function list(x) { return x == null ? [] : Array.isArray(x) ? x : [x]; }
  function isIn(name) { return !files()[name] || st(name).state === 2; }

  /* A bundle's files run in their own order and nobody else's. They were
     injected with async=false, which a browser orders across the WHOLE
     page: a lesson opened while the warm-up was still fetching another
     subject's several megabytes waited for all of it (the "severe delay"
     on IT's notes, 17 November 2026). Now every file of a bundle is asked
     for at once (a preload) and they run one after another as each
     arrives, so one bundle never queues behind another. */
  function preload(src) {
    if (HOOK && HOOK.inject) return;
    try {
      var l = document.createElement("link");
      l.rel = "preload"; l.as = "script"; l.href = src;
      document.head.appendChild(l);
    } catch (e) { /* only a hint */ }
  }
  function inject(src, done) {
    if (HOOK && HOOK.inject) { HOOK.inject(src, done); return; }
    var s = document.createElement("script");
    s.src = src;
    s.async = true;             /* the order is the bundle's own: see runAll */
    s.onload = function () { done(null); };
    s.onerror = function () { done(new Error("Could not load " + src)); };
    document.head.appendChild(s);
  }
  function runAll(list, done) {
    var i = 0, failed = null, left = list.length;
    /* the test loader evaluates each file in the order it is handed them */
    if (HOOK && HOOK.inject) {
      list.forEach(function (src) {
        inject(src, function (err) { if (err && !failed) failed = err; if (--left === 0) done(failed); });
      });
      return;
    }
    list.forEach(preload);
    (function next() {
      if (i >= list.length) { done(failed); return; }
      inject(list[i++], function (err) { if (err && !failed) failed = err; next(); });
    })();
  }

  function loadOne(name) {
    if (isIn(name)) return Promise.resolve();
    var b = st(name);
    if (b.p) return b.p;
    b.state = 1;
    b.p = new Promise(function (resolve, reject) {
      var list = files()[name], failed = null;
      function finish() {
        if (failed) { b.state = 0; b.p = null; reject(failed); return; }
        b.state = 2;
        listeners.slice().forEach(function (fn) {
          try { fn(name); } catch (e) { console.error("Kurenai OS: a lazy listener failed", e); }
        });
        resolve();
      }
      if (!list.length) { finish(); return; }
      runAll(list, function (err) { failed = err; finish(); });
    });
    return b.p;
  }

  function ready(x) { return list(x).every(isIn); }
  function need(x) {
    return Promise.all(list(x).map(loadOne)).then(function () { /* nothing to hand back */ });
  }
  function pending(x) { return list(x).filter(function (n) { return !isIn(n); }); }

  /* ---------------- stand-ins ---------------- */
  /* stub(light, heavy, label, sum): `light` holds the facts kept; `heavy`
     maps each field left out to the bundle that brings it ({name: bundle});
     `sum` is the summary a structural reader asks for (KOS.lazy.summary).
     Anything else reads as the real object would: absent. */
  var META = typeof WeakMap === "function" ? new WeakMap() : null;
  function stub(light, heavy, label, sum, empty) {
    var p = new Proxy(light, {
      get: function (t, k) {
        if (typeof k === "symbol" || k in t || !heavy[k]) return t[k];
        miss(heavy[k], label + "." + k);
        /* `empty` gives a field its empty shape (a list read as a list) */
        return empty && Object.prototype.hasOwnProperty.call(empty, k) ? empty[k] : undefined;
      },
      has: function (t, k) {
        if (k in t) return true;
        if (typeof k !== "symbol" && heavy[k]) miss(heavy[k], label + "." + k);
        return false;
      }
    });
    if (META) META.set(p, { light: light, heavy: heavy, label: label, sum: sum || null });
    return p;
  }
  function isStub(o) { return !!o && typeof o === "object" && !!META && META.has(o); }
  /* the structural summary of a content stand-in ({pages, cards, quiz, exam,
     runs, practice}); null for the real thing */
  function summary(o) { var m = isStub(o) ? META.get(o) : null; return m ? m.sum : null; }
  /* a registry entry built from more than one file (a capstone, a Rider
     project): what a file brings is laid over what is there, and the
     result stays a stand-in while another bundle still owes it a field */
  function merge(prev, o) {
    if (!isStub(prev)) return Object.assign({}, prev || {}, o);
    var m = META.get(prev);
    var out = Object.assign({}, m.light, o), left = {}, owed = false;
    Object.keys(m.heavy).forEach(function (k) {
      if (k in o || isIn(m.heavy[k])) return;
      left[k] = m.heavy[k]; owed = true;
    });
    return owed ? stub(out, left, m.label, m.sum) : out;
  }
  /* a card (or row) whose text is in a bundle not loaded yet: its key and
     place are known, its question and answer are a miss when read */
  function pendingText(o, bundle, label) {
    ["q", "a"].forEach(function (k) {
      Object.defineProperty(o, k, {
        enumerable: true, configurable: true,
        get: function () { miss(bundle, label + "." + k); return ""; },
        set: function (v) { Object.defineProperty(o, k, { value: v, writable: true, enumerable: true, configurable: true }); }
      });
    });
    Object.defineProperty(o, "pend", { value: bundle, enumerable: false, configurable: true });
    return o;
  }
  function heavyMap(names, bundle, over) {
    var out = {};
    String(names || "").split(",").forEach(function (k) { if (k) out[k] = (over && over[k]) || bundle; });
    return out;
  }

  /* install(index): put the stand-ins where the bundles will register.
     Called by js/data/lazy-index.js; nothing to do in an eager boot, where
     the real files run straight after. */
  function install(ix) {
    if (!LAZY || !ix) return;
    var known = files();
    var C = window.KOS_CONTENT = window.KOS_CONTENT || {};
    /* in the order the files would have filled it: a deck and the due
       queue break ties by it */
    (ix.content || []).forEach(function (row) {
      var key = row[0], bundle = row[1], r = row[2];
      if (!known[bundle]) return;
      C[key] = stub(Object.assign({}, r.l || {}), heavyMap(r.h, bundle), key,
        { bundle: bundle, pages: r.p || 0, cards: r.f || 0, quiz: r.q || 0, exam: r.e || 0, runs: r.r || [], practice: r.pr || null });
    });
    var K = window.KOS_CODE, code = ix.code || {};
    if (K && known["content-code"]) {
      ["CONCEPTS", "TASKS", "CARDS", "CAPSTONES", "PROJECTS"].forEach(function (reg) {
        var rows = code[reg] || {};
        K[reg] = K[reg] || {};
        Object.keys(rows).forEach(function (id) {
          var r = rows[id];
          K[reg][id] = stub(Object.assign({}, K[reg][id] || {}, r.l || {}), heavyMap(r.h, "content-code", r.hb), "KOS_CODE." + reg + "." + id);
        });
      });
      if (code.DATASETS && code.DATASETS.length) {
        K.DATASETS = stub(K.DATASETS || {}, heavyMap(code.DATASETS.join(","), "content-code"), "KOS_CODE.DATASETS");
      }
    }
    var X = window.KOS_EXAMS = window.KOS_EXAMS || {}, ex = ix.exams || {};
    if (ex.index && known["exam-index"] && !X.index) {
      /* the past-paper index: its papers, questions and A-level-only leaves
         are here from the start, because readiness, a scope and a goal are
         COMPUTED from them (a figure worked out without them would be a
         different figure). Only the topic-pack list waits. */
      X.index = stub(Object.assign({}, ex.index.l || {}), heavyMap(ex.index.h, "exam-index"), "KOS_EXAMS.index", null, { packs: [] });
    }
    if (ex.deep && known["exams-deep"]) {
      X.deep = X.deep || {};
      Object.keys(ex.deep).forEach(function (pid) {
        var r = ex.deep[pid], leaves = {};
        Object.keys(r.leaves || {}).forEach(function (ref) {
          leaves[ref] = stub({}, heavyMap(r.leaves[ref], "exams-deep"), "KOS_EXAMS.deep." + pid + "." + ref);
        });
        X.deep[pid] = stub(Object.assign({ leaves: leaves }, r.l || {}), heavyMap(r.h, "exams-deep"), "KOS_EXAMS.deep." + pid);
      });
    }
  }

  var missTimer = null, missWant = {};
  function miss(bundle, what) {
    if (isIn(bundle)) return;
    if (MISSES.length < 400) MISSES.push({ bundle: bundle, what: what });
    if (HOOK && HOOK.onMiss) HOOK.onMiss(bundle, what);
    missWant[bundle] = true;
    if (missTimer) return;
    /* after the code that missed has finished: load, then draw the page
       again with the real thing */
    missTimer = setTimeout(function () {
      missTimer = null;
      var want = Object.keys(missWant); missWant = {};
      need(want).then(function () {
        if (KOS.rerender) KOS.rerender({ preserve: true });
      }, function (e) { console.error("Kurenai OS: " + e.message); });
    }, 0);
  }

  /* ---------------- warming up ----------------
     Once the first page is up and the reader has had a few quiet seconds,
     the bundles are fetched one at a time in idle moments, the subject last
     studied first. Boot stays light; after that every page opens at once and
     every later background pass (a 30-minute tick, a sync) finds the real
     thing. Skipped when the device asks to save data. A test boot warms
     only if its hook says so. */
  var warmed = false;
  function idle(fn) {
    if (typeof window.requestIdleCallback === "function") window.requestIdleCallback(fn, { timeout: 4000 });
    else setTimeout(fn, 400);
  }
  function warm(first) {
    if (!LAZY || warmed) return;
    if (HOOK && !HOOK.warm) return;
    var c = navigator.connection;
    if (c && c.saveData) return;
    warmed = true;
    var order = names().slice();
    list(first).forEach(function (n, i) {
      var at = order.indexOf(n);
      if (at > -1) { order.splice(at, 1); order.splice(i, 0, n); }
    });
    (function next() {
      var todo = order.filter(function (n) { return !isIn(n); });
      if (!todo.length) return;
      idle(function () {
        /* a page waiting for its own bundle has the connection to itself */
        if (waiting()) { setTimeout(next, 400); return; }
        loadOne(todo[0]).then(next, function () { /* offline: a page asks again when it is opened */ });
      });
    })();
  }

  /* ---------------- what a page needs ---------------- */
  /* A function of the page's argument, giving bundle names. A page not
     listed needs nothing up front (a miss still loads what it reads). The
     subject bundles are "content-<subject id>". */
  function contentOf(sid) { return sid ? "content-" + sid : null; }
  function subjectOfArg(arg) {
    return arg && typeof arg === "object" ? arg.subject || arg.sid || null : typeof arg === "string" ? arg : null;
  }
  var CODE = ["content-code"];
  /* the reworked pages and their engine ride their own bundle (design 45–47) */
  var EXAMS = ["exam-index", "exams-deep", "exams-pages"];
  /* the bundles holding the words of the cards a review page shows: the
     ones due and the ones set aside, by the subject each belongs to */
  function reviewBundles(arg) {
    var out = [];
    if (!KOS.srs) return out;
    var add = function (c) { if (c && c.pend && out.indexOf(c.pend) === -1) out.push(c.pend); };
    KOS.srs.dueCards().forEach(add);
    if (KOS.srs.leeches) KOS.srs.leeches().forEach(add);
    /* the questions back today (5.19 item 4) are drawn from their topics'
       quiz and exam items: only their run reads them */
    if (arg && arg.run === "questions" && KOS.questions) KOS.questions.dueToday().list.forEach(function (q) {
      var b = /^(compsci|maths|it)$/.test(q.sid) ? contentOf(q.sid) : null;
      if (b && out.indexOf(b) === -1) out.push(b);
    });
    return out;
  }
  var NEEDS = {
    ref: function (arg) { return [contentOf(subjectOfArg(arg))]; },
    subject: function (arg) { return [contentOf(subjectOfArg(arg))]; },
    code: function () { return CODE; },
    /* one assessment's pages assemble its Companion and its papers from its
       subject's notes and question banks */
    exams: function (arg) {
      var X = KOS.exams, id = typeof arg === "string" ? arg.split("/")[0] : arg && arg.id;
      var a = id && X && X.get ? X.get(id) : null;
      /* the hub's own pages (Season's quick recall, the planner) read the
         cards of the exams still to come */
      var list = a ? [a] : X && X.upcoming ? X.upcoming() : [];
      return EXAMS.concat(list.map(function (x) { return x && x.subject ? contentOf(x.subject) : null; }));
    },
    tracker: function () { return ["exam-index", "exams-pages"]; },
    review: reviewBundles,
    due: reviewBundles,
    cardstats: reviewBundles
  };
  /* W8 (AP-01 stage 2): PAGE MODULES on first use. A page whose module
     (and the modules only it uses) rides its own bundle names it here; a
     subject desk or a topic page drawn by a study space's module needs that
     space's bundle too. Until the bundle is in, KOS.views.<view> is a
     stand-in (below), so a route to it is valid from the first moment. */
  var PAGES = {
    money: ["page-money"], governor: ["page-governor"], code: ["page-code"],
    mind: ["page-mind"], japanese: ["page-ja"], help: ["page-help"],
    shrine: ["page-shrine"], reports: ["page-reports"],
    mediasync: ["page-sync"], aniprofile: ["page-sync"], vndbprofile: ["page-sync"]
  };
  var SPACE_DESK = { code: "page-code", mind: "page-mind", ja: "page-ja" };
  var SPACE_TOPIC = { mind: "page-mind" };
  function pagesFor(viewId, arg) {
    var out = (PAGES[viewId] || []).slice(), sid = subjectOfArg(arg);
    if (viewId === "subject" && SPACE_DESK[sid]) out.push(SPACE_DESK[sid]);
    if (viewId === "ref" && SPACE_TOPIC[sid]) out.push(SPACE_TOPIC[sid]);
    return out;
  }
  function needsFor(viewId, arg) {
    var fn = NEEDS[viewId];
    var want = (fn ? fn(arg) : []).concat(pagesFor(viewId, arg));
    /* a page may add its own (KOS.lazy.needs.<view> = fn) */
    var extra = KOS.lazy.needs[viewId];
    if (extra) want = want.concat(extra(arg) || []);
    return pending(want.filter(Boolean));
  }

  /* the page while its bundles load: a quiet line, then the real page.
     `draw` is the page's own first draw, run once the bundles are in and
     only if the reader is still on that page (`key` names it, so a redraw
     of the waiting page keeps what waits for it). */
  var afterDraw = [], wait = null;
  function waiting() { return !!wait && wait.live(); }
  function placeholder(main, want, draw, key) {
    var box = document.createElement("div");
    box.className = "k-lazy-wait";
    box.setAttribute("data-ui", "lazy.wait");
    box.setAttribute("role", "status");
    box.setAttribute("aria-busy", "true");
    box.textContent = "Loading…";
    main.appendChild(box);
    if (!wait || wait.key !== key) afterDraw = [];
    var mine = wait = { key: key, live: KOS.view && KOS.view.token ? KOS.view.token() : function () { return true; } };
    need(want).then(function () {
      if (wait !== mine) return;                /* drawn again since, or another page waits */
      wait = null;
      var run = afterDraw; afterDraw = [];
      if (!mine.live()) return;                 /* the reader has moved on */
      draw();
      run.forEach(function (fn) { try { fn(); } catch (e) { console.error(e); } });
    }, function (e) {
      if (wait !== mine) return;
      wait = null; afterDraw = [];
      if (!mine.live()) return;
      box.removeAttribute("aria-busy");
      box.textContent = "This page could not be loaded. Check the connection and open it again.";
      console.error("Kurenai OS: " + e.message);
    });
  }

  /* the stand-in views and exports of the page bundles. KOS.show never
     calls a stand-in view (it waits for the bundle and calls the real one);
     one called directly waits the same way. The real module replaces each
     as it loads, in a lazy boot or an eager one alike. */
  KOS.views = KOS.views || {};
  Object.keys(PAGES).forEach(function (view) {
    var f = function (main, arg) {
      placeholder(main, PAGES[view], function () {
        main.innerHTML = "";
        if (KOS.views[view] !== f) KOS.views[view](main, arg);
      }, "page:" + view);
    };
    f.lazyStandIn = true;
    KOS.views[view] = f;
  });
  /* the shop, opened at a department from the labs, a slot or the
     Governor's gates (governor-ui.js, in page-governor) */
  var openShop = KOS.openShop = function (sel) {
    need(["page-governor"]).then(function () {
      if (KOS.openShop !== openShop) KOS.openShop(sel); else KOS.show("governor", "shop");
    }, function () { KOS.show("governor", "shop"); });
  };

  KOS.lazy = {
    mode: LAZY ? "lazy" : "eager",
    pagesFor: pagesFor,
    names: names,
    files: function (name) { return (files()[name] || []).slice(); },
    ready: ready,
    pending: pending,
    need: need,
    all: function () { return need(names()); },
    warm: warm,
    on: function (fn) { listeners.push(fn); },
    stub: stub,
    isStub: isStub,
    summary: summary,
    merge: merge,
    pendingText: pendingText,
    install: install,
    miss: miss,
    misses: function () { return MISSES.slice(); },
    clearMisses: function () { MISSES.length = 0; },
    needs: {},
    needsFor: needsFor,
    contentOf: contentOf,
    placeholder: placeholder,
    /* is the page on screen still waiting for its bundles? */
    waiting: waiting,
    /* a navigation's focus and announcement wait for the real page */
    afterDraw: function (fn) { if (waiting()) afterDraw.push(fn); else fn(); }
  };
})();
