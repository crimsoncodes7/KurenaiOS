#!/usr/bin/env python3
"""Build the consolidated findings for the 2026-12 audit (Phase 2).

    python3 -I docs/audit/2026-12/harness/consolidate.py

Reads docs/audit/2026-12/findings/: for each area the final <area>.json
({summary, coverage, findings}) written when its auditor finished; an area
with only <area>.jsonl (the auditor was stopped, findings saved as it went)
uses those lines and is marked PARTIAL. Each finding carries its own id
(the area prefix, numbered on from November's last id, so ids are unique
across both audits). Carbon's verdicts, when filed, are read from
carbon/verdicts-<batch>.json ({id: {verdict, severity?, note}}) and shown
beside each finding. Writes FINDINGS.md, findings.json and findings.csv
next to the findings folder."""
import csv, glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
BASE = os.path.dirname(HERE)
FD = os.path.join(BASE, "findings")

AREAS = [
    ("productivity", "PR", "Focus, Reminders, Routines, Daily Review, Calendar, Pacing", 1),
    ("exams-files-ink", "EX", "Exams hub, Files, ink/Pencil surfaces", 1),
    ("study-core", "ST", "Study desks, topic page, Review, Assignments, the Error Log", 1),
    ("sync-disruption", "SY", "Background redraws / cloud sync disrupting work", 1),
    ("data-integrity", "DI", "Reliability and data integrity (store, merge, sync, IndexedDB, integrations)", 1),
    ("architecture-perf", "AP", "Architecture, maintainability, performance, loading, docs drift", 1),
    ("money-goals", "MG", "Money; Goals pages only", 2),
    ("goals", "GO", "Goals: every goal type's measurement, editor, notices, joins", 2),
    ("ja-mind", "JM", "Japanese study space", 2),
    ("mind", "MI", "Mind study space", 2),
    ("code-space", "CO", "Code study space", 2),
    ("content-cs-it", "CC", "A-Level CS and OCR IT content quality", 3),
    ("content-maths", "CM", "A-Level Maths content quality", 3),
    ("home-reports", "HR", "Home and Reports", 3),
    ("shell", "SH", "App shell, navigation, search, toasts, dialogs", 3),
    ("assistant-archive", "AA", "Assistant, notifications, Archive (data, backups, storage, connections)", 3),
    ("collection", "CL", "Collection vaults, Shrine, Wishlist, Sync", 4),
    ("creatives", "CR", "Creatives study space", 4),
    ("achievements-governor", "AG", "Badge Wall and the Governor's Seat", 4),
    ("shop-cosmetics", "SC", "Gold Shop, cosmetics, themes", 4),
    ("a11y-hci", "AX", "Cross-cutting accessibility and HCI", 4),
]
SEV = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}


def read_jsonl(path):
    out = {}
    for line in open(path):
        line = line.strip()
        if not line:
            continue
        try:
            f = json.loads(line)
        except Exception:
            continue
        out[f.get("id") or f.get("title")] = f   # a later line for the same id replaces the earlier one
    return list(out.values())


def load(area):
    st, summary, cov, fs = _load(area)
    # the copy pass (the user's own data, slot 7) writes <area>.copy.jsonl, ids <prefix>-90 upward
    cp = os.path.join(FD, area + ".copy.jsonl")
    if os.path.exists(cp):
        have = set(f.get("id") for f in fs)
        fs = fs + [dict(f, copyPass=True) for f in read_jsonl(cp) if f.get("id") not in have]
    return st, summary, cov, fs


def _load(area):
    final, part = os.path.join(FD, area + ".json"), os.path.join(FD, area + ".jsonl")
    if os.path.exists(final):
        o = json.load(open(final))
        return "complete", o.get("summary", ""), o.get("coverage", ""), o.get("findings", [])
    if os.path.exists(part):
        return "partial", "", "", read_jsonl(part)
    return "not run", "", "", []


def verdicts():
    v = {}
    for p in sorted(glob.glob(os.path.join(BASE, "carbon", "verdicts-*.json"))):
        v.update(json.load(open(p)))
    return v


def val(x):
    return x if isinstance(x, str) else json.dumps(x, ensure_ascii=False)


def main():
    V = verdicts()
    rows, table = [], []
    for area, pre, label, batch in AREAS:
        st, summary, cov, fs = load(area)
        fs = sorted(fs, key=lambda f: (SEV.get(f.get("severity"), 9), f.get("id", "")))
        c = {k: 0 for k in SEV}
        mine = []
        for f in fs:
            f = dict(f, area=area, batch=batch, areaStatus=st)
            if f.get("id") in V:
                f["carbon"] = V[f["id"]]
            if f.get("severity") in c:
                c[f["severity"]] += 1
            mine.append(f)
        rows.extend(mine)
        table.append((pre, label, batch, st, c, mine, summary, cov))

    md = ["# KurenaiOS audit, December 2026 (Phase 2): consolidated findings\n",
          "Generated by `harness/consolidate.py` from `findings/`. Do not hand-edit; re-run the script.\n",
          "Audited commit: `fa4264d0` (main, sw kos-qol-4). November's audit ran on `4c3fc33`; Phase 1 is"
          " `f479433b..fa4264d0`. See README.md.\n",
          "Status: **complete** = the auditor finished and re-checked its P0/P1s; **partial** = stopped part-way"
          " (its findings are real but coverage is not); **not run** = not audited yet (no findings does NOT mean"
          " it passed).\n",
          "| ID | Area | Batch | Status | P0 | P1 | P2 | P3 | Total |", "|---|---|---|---|---|---|---|---|---|"]
    tot = {k: 0 for k in SEV}
    for pre, label, batch, st, c, mine, _, _ in table:
        md.append(f"| {pre} | {label} | {batch} | {st} | {c['P0']} | {c['P1']} | {c['P2']} | {c['P3']} | {len(mine)} |")
        for k in SEV:
            tot[k] += c[k]
    md.append(f"| | **All** | | | {tot['P0']} | {tot['P1']} | {tot['P2']} | {tot['P3']} | {sum(tot.values())} |\n")
    md.append("## Every P0 and P1\n")
    for f in rows:
        if f.get("severity") in ("P0", "P1"):
            cv = f" · Carbon: {f['carbon'].get('verdict')}" if f.get("carbon") else ""
            reg = f" · regression of {f['regressionOf']}" if f.get("regressionOf") else ""
            md.append(f"- **{f.get('id')}** [{f.get('severity')}] {f.get('title')}{reg}{cv}")
    md.append("")
    for pre, label, batch, st, c, mine, summary, cov in table:
        if st == "not run":
            continue
        md.append(f"## {pre} · {label} ({st})\n")
        if summary:
            md.append(val(summary) + "\n")
        if cov:
            md.append("**Coverage.** " + val(cov) + "\n")
        for f in mine:
            md.append(f"### {f.get('id')} [{f.get('severity')}] {f.get('title')}\n")
            for k, lab in (("detail", "What"), ("rootCause", "Root cause"), ("evidence", "Evidence"), ("fix", "Fix"),
                           ("devices", "Devices"), ("accounts", "Accounts"), ("regressionOf", "Regression of"),
                           ("phase1", "Phase 1 change")):
                if f.get(k):
                    md.append(f"- **{lab}:** {val(f[k])}")
            if f.get("carbon"):
                md.append(f"- **Carbon:** {val(f['carbon'])}")
            md.append("")
    open(os.path.join(BASE, "FINDINGS.md"), "w").write("\n".join(md) + "\n")
    json.dump(rows, open(os.path.join(BASE, "findings.json"), "w"), indent=1, ensure_ascii=False)
    keys = ["id", "area", "batch", "severity", "category", "title", "rootCause", "evidence", "devices", "accounts",
            "regressionOf", "phase1", "effort"]
    with open(os.path.join(BASE, "findings.csv"), "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(keys + ["carbon"])
        for f in rows:
            w.writerow([f.get(k) if isinstance(f.get(k), (str, int, type(None))) else val(f.get(k)) for k in keys]
                       + [(f.get("carbon") or {}).get("verdict", "")])
    print("consolidate: %d findings; P0 %d, P1 %d, P2 %d, P3 %d" % (len(rows), tot["P0"], tot["P1"], tot["P2"], tot["P3"]))


if __name__ == "__main__":
    main()
