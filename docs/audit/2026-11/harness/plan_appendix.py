"""Regenerate PLAN.md's appendix (every open finding by workstream) from
data/plan-mapping.json and findings.json. Run after any mapping change:
python3 -I docs/audit/2026-11/harness/plan_appendix.py"""
import json, os
B = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = json.load(open(os.path.join(B, "data/plan-mapping.json")))
F = {f["id"]: f for f in json.load(open(os.path.join(B, "findings.json"))) if not f.get("resolved")}
m = {x["id"]: x for x in d["map"]}
missing = sorted(set(F) - set(m))
if missing:
    raise SystemExit("unmapped open findings: " + ", ".join(missing))
order = ["W0","W1","W2","W3","W4","W5","W6","W7","W8","W9","QOL","BACKLOG"]
names = {"W0":"Safety net","W1":"Data integrity and the economy","W2":"Redraw policy and view lifecycle","W3":"Layering, layout tiers and touch","W4":"Money revamp","W5":"Cosmetics, shop and art","W6":"Content quality","W7":"Connected OS and honest numbers","W8":"Maintainability, performance and docs","W9":"Polish and HCI","QOL":"QoL","BACKLOG":"Backlog"}
sev = {"P0":0,"P1":1,"P2":2,"P3":3}
L = []
for w in order:
    ids = sorted([i for i in m if m[i]["ws"] == w and i in F], key=lambda i: (sev.get(F[i]["severity"], 9), i))
    if not ids: continue
    L += ["\n### %s — %s (%d)\n" % (w, names[w], len(ids)), "| Id | Sev | Title | RC | Fixed by / depends on | Decision |", "|---|---|---|---|---|---|"]
    for i in ids:
        x = m[i]; t = F[i]["title"].replace("|", "/")[:140]
        dep = "; ".join(s for s in [("fixed by " + x["fixedBy"]) if x["fixedBy"] else "", ("after " + x["dependsOn"]) if x["dependsOn"] else ""] if s)
        flags = (" ✎design" if x["design"] else "") + (" ✦art" if x["art"] else "")
        L.append("| %s | %s | %s%s | %s | %s | %s |" % (i, F[i]["severity"], t, flags, x["rc"], dep, "yes" if x["decision"] else ""))
L.append("\n### Decisions recorded per finding\n")
for i in sorted(m):
    if m[i]["decision"] and i in F: L.append("- **%s:** %s" % (i, m[i]["decision"]))
p = os.path.join(B, "PLAN.md"); s = open(p).read()
head = s.split("## Appendix — every open finding by workstream")[0]
open(p, "w").write(head + "## Appendix — every open finding by workstream\n\nGenerated by `harness/plan_appendix.py` from [`data/plan-mapping.json`](data/plan-mapping.json). \"fixed by\" names the finding whose fix also closes it.\n" + "\n".join(L) + "\n")
print("appendix:", sum(1 for i in m if i in F), "findings")
