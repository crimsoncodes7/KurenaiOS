#!/usr/bin/env node
/* Kurenai OS — tools/gen_exam_reports.mjs
   The examiner's report NOTES (tools/exam-index/reports/<paper>.md, our own
   paraphrase, each point citing its series and question; invariant 125)
   → js/data/exam-reports.js, the form the Companion, the playbook's
   Misconceptions Blacklist and the discriminators read.

     node tools/gen_exam_reports.mjs           write js/data/exam-reports.js
     node tools/gen_exam_reports.mjs --check   exit 1 if it is out of date

   A note file is: "## <Month> <Year>" series headings (or "## Habits …"
   for points across series), "### Q<n> (<marks>) · <leaf> <title>"
   question headings, and "- " points (continuation lines indented). The
   reports themselves never enter the repo; only these notes do.          */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "tools/exam-index/reports");
const OUT = path.join(ROOT, "js/data/exam-reports.js");
const MONTHS = { january: "01", february: "02", march: "03", april: "04", may: "05", june: "06", july: "07",
  august: "08", september: "09", october: "10", november: "11", december: "12" };

function parse(text) {
  const out = { title: "", habits: [], notes: [] };
  let series = null, cur = null, bucket = null, point = null;
  /* a habit is a point for the whole paper (or one series), not a question */
  const habitsOf = (sitting) => ({ push: (text) => out.habits.push({ sitting, text }) });
  const flush = () => { if (point != null && bucket) bucket.push(point.replace(/\s+/g, " ").trim()); point = null; };
  for (const raw of text.split("\n")) {
    const line = raw.replace(/\s+$/, "");
    let m;
    if ((m = /^# (.+)$/.exec(line))) { out.title = m[1].replace(/\s+—.*$/, "").trim(); continue; }
    if ((m = /^## (.+)$/.exec(line))) {
      flush(); cur = null;
      const sm = /^(\w+) (\d{4})/.exec(m[1]);
      /* a series heading; "— on the day" points are that series' habits;
         a "Section …" heading inside a series keeps it */
      if (sm && MONTHS[sm[1].toLowerCase()]) { series = sm[2] + "-" + MONTHS[sm[1].toLowerCase()]; bucket = habitsOf(series); }
      else if (/^section/i.test(m[1])) bucket = null;
      else { series = null; bucket = /habit/i.test(m[1]) ? habitsOf(null) : null; }
      continue;
    }
    if ((m = /^### (Q[\w.]+)(?:[–-](Q[\w.]+))?\s*(?:\(([\d+]+)\))?\s*·\s*(?:([A-Z]?\d+(?:\.\d+)*)\s+)?(.*)$/.exec(line))) {
      flush();
      const marks = m[3] ? m[3].split("+").reduce((a, b) => a + Number(b), 0) : null;
      cur = { sitting: series, q: m[1], to: m[2] || null, marks, leaf: m[4] || null, title: m[5].trim(), points: [] };
      out.notes.push(cur);
      bucket = cur.points;
      continue;
    }
    if (/^---/.test(line)) { flush(); continue; }
    if ((m = /^- (.*)$/.exec(line))) { flush(); point = m[1]; continue; }
    if (point != null && /^\s+\S/.test(line)) { point += " " + line.trim(); continue; }
    if (!line.trim()) flush();
  }
  flush();
  return out;
}

const files = fs.readdirSync(DIR).filter((f) => /^[a-z]+-\w+-\d+\.md$/.test(f)).sort();
const data = {};
for (const f of files) data[f.replace(/\.md$/, "")] = parse(fs.readFileSync(path.join(DIR, f), "utf8"));
const body = "/* GENERATED by tools/gen_exam_reports.mjs from tools/exam-index/reports/*.md —\n" +
  "   our own paraphrase of the examiner's reports, each point citing its series\n" +
  "   and question (invariant 125). Do not edit by hand: edit the notes and rerun. */\n" +
  "window.KOS_EXAMS = window.KOS_EXAMS || {};\n" +
  "window.KOS_EXAMS.reports = " + JSON.stringify(data) + ";\n";

if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== body) { console.error("js/data/exam-reports.js is out of date: run node tools/gen_exam_reports.mjs"); process.exit(1); }
  console.log("exam-reports.js is current");
} else {
  fs.writeFileSync(OUT, body);
  const n = Object.values(data).reduce((s, d) => s + d.notes.length, 0);
  console.log("wrote js/data/exam-reports.js: " + files.length + " papers, " + n + " question notes");
}
