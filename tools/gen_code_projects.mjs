#!/usr/bin/env node
/* tools/gen_code_projects.mjs — the Rider projects' scaffolds, from their
   real files (tools/code-projects/<folder>/, built and validated with the
   .NET SDK by tools/validator_check.mjs) into the app's data:
   js/data/content/code-projects-files.js, one KOS_CODE.project(id, {files})
   per project. Generated — edit the folder, then run this.
     node tools/gen_code_projects.mjs                                        */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const MAP = { "hello-kurenai": "rp-bridge-hello", "library-legacy": "rp-u10-library", "revision-planner": "rp-c4-planner" };
const SKIP = new Set(["bin", "obj", "out", "reports", ".idea"]);
let js = "/* Kurenai OS — data/content/code-projects-files.js\n   GENERATED by tools/gen_code_projects.mjs from tools/code-projects/ — do not edit.\n   The Rider projects' scaffold files; the briefs and milestones are in the\n   lesson files (code-ub.js), the validator in assets/code/validator/. */\n(function () {\n  \"use strict\";\n  var K = window.KOS_CODE;\n";
for (const [folder, id] of Object.entries(MAP)) {
  const dir = path.join(ROOT, "tools/code-projects", folder), files = {};
  (function walk(rel) {
    for (const f of fs.readdirSync(path.join(dir, rel)).sort()) {
      if (SKIP.has(f)) continue;
      const r = rel ? rel + "/" + f : f, full = path.join(dir, r);
      if (fs.statSync(full).isDirectory()) walk(r);
      else if (r !== "kurenai.project.json" && !r.startsWith(".kurenai/")) files[r] = fs.readFileSync(full, "utf8");
    }
  })("");
  js += "  K.project(" + JSON.stringify(id) + ", { files: " + JSON.stringify(files, null, 1).replace(/\n/g, "\n  ") + " });\n";
  console.log(id + ": " + Object.keys(files).length + " files");
}
js += "})();\n";
fs.writeFileSync(path.join(ROOT, "js/data/content/code-projects-files.js"), js);
