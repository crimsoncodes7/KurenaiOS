#!/usr/bin/env node
/* tools/gen_moved_cards.mjs — writes js/data/moved-cards.js (roadmap 5.19
   item 4): the Maths flashcards that are several-step problems, which are
   not quick recall (under about 30 seconds a card) and so live as exam
   questions instead (KOS.questions.moveCards). A card moves when its
   question asks for work (Find, Solve, Show, Prove, Integrate, …) and its
   answer takes three steps or more (=, ⇒, ;, "then", "so"), or it is a
   proof. The list only grows: a card once moved stays moved, so its
   schedule (copied to the question at boot) is never orphaned.
     node tools/gen_moved_cards.mjs           write
     node tools/gen_moved_cards.mjs --check   exit 1 when the file is stale */
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const require = createRequire(import.meta.url);
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "js/data/moved-cards.js");
const { boot } = require("./lib/app-harness.js");

const VERB = /^(Find|Solve|Show|Prove|Integrate|Differentiate|Calculate|Evaluate|Work out|Expand|Factorise|Simplify|Determine)\b/i;
const STEP = /=|\\Rightarrow|\\implies|;|\bthen\b|\bso\b/g;
const app = await boot({ clock: "2026-11-16T10:00:00" });
const C = app.window.KOS_CONTENT;
const was = app.window.KOS_MOVED_CARDS || {};
const out = {};
Object.keys(was).forEach((t) => { out[t] = was[t].slice(); });
for (const key of Object.keys(C).filter((k) => k.startsWith("maths:")).sort()) {
  (C[key].flashcards || []).forEach((c, i) => {
    const pos = c[2] == null ? i : c[2];
    if (typeof pos !== "number") return;
    const q = String(c[0]), a = String(c[1]);
    const steps = (a.match(STEP) || []).length;
    if (VERB.test(q) && (steps >= 3 || /^Prove\b/i.test(q))) (out[key] = out[key] || []).push(pos);
  });
}
const keys = Object.keys(out).sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
let n = 0;
const body = keys.map((k) => { const v = [...new Set(out[k])].sort((a, b) => a - b); n += v.length; return "  " + JSON.stringify(k) + ": " + JSON.stringify(v); }).join(",\n");
const text = "/* GENERATED by tools/gen_moved_cards.mjs — do not edit by hand.\n   The Maths flashcards moved to their topic's exam questions (roadmap 5.19\n   item 4, js/core/questions.js): \"<topic>\": [card positions]. " + n + " cards. */\nwindow.KOS_MOVED_CARDS = {\n" + body + "\n};\n";
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== text) { console.log("gen_moved_cards: js/data/moved-cards.js is stale"); process.exit(1); }
  console.log("gen_moved_cards: current (" + n + " cards)"); process.exit(0);
}
fs.writeFileSync(OUT, text);
console.log("gen_moved_cards: " + n + " cards in " + keys.length + " topics");
process.exit(0);
